/**
 * Spike: OrcaSlicer's engine (Muon3D, WebAssembly, `st` variant) slicing the plate of the real app in the browser.
 * Needs `node scripts/fetch-slicer.mjs` first. Writes G-code and measurements to SPIKE_OUT (default: the OS temp folder).
 */
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import zlib from 'node:zlib'
import { test, expect, type App } from './helpers'

const OUT = process.env.SPIKE_OUT ?? path.join(os.tmpdir(), 'slicer-spike')
const ENGINE = path.resolve(import.meta.dirname, '../public/slicer/engine')
const PROFILES = path.resolve(import.meta.dirname, '../public/slicer/profiles')
fs.mkdirSync(OUT, { recursive: true })

interface Run {
  gcode: string
  gcodeBytes: number
  stats: { printTimeSeconds: number | null; printTimeText: string | null; filamentMm: number | null; filamentG: number | null; filamentCm3: number | null; layers: number | null; maxZ: number | null }
  layerCount: number | null
  layerZ: number[]
  extrusionSegments: number
  travelSegments: number
  warnings: { kind: string; message: string }[]
  engineTimings: { load: number; slice: number; export: number; total: number }
  heapBytes?: number
  ms: { loadEngine: number; presets: number; slice: number }
  progressEvents: number
  filaments: number
}

async function addBox(app: App, size: [number, number, number], position: [number, number, number]) {
  await app.ev((c, a) => c.doc.getState().addFeature('box', { width: a.size[0], depth: a.size[1], height: a.size[2], position: a.position }), { size, position })
  await app.idle()
}
const slice = (app: App, key: 'a1' | 'mk4s' | 'mk4') => app.ev((_c, k) => (window as any).__slicerSpike.run(k) as Promise<Run>, key) // eslint-disable-line
const save = (name: string, r: Run) => {
  fs.writeFileSync(path.join(OUT, `${name}.gcode`), r.gcode)
  const { gcode: _g, ...rest } = r
  fs.writeFileSync(path.join(OUT, `${name}.json`), JSON.stringify(rest, null, 1))
}
async function selectField(app: App, label: string, option: string) {
  await app.inspector().locator('.field', { has: app.page.locator('.field-label', { hasText: label }) }).locator('button.sel').click()
  await app.page.getByRole('option', { name: option }).click()
}
const count = (s: string, re: RegExp) => (s.match(re) ?? []).length

test('slicer spike: 20 mm cube with the A1 and MK4S presets', async ({ app, page }) => {
  test.setTimeout(240_000)
  await app.open()
  await addBox(app, [20, 20, 20], [0, 0, 0])
  await app.page.waitForFunction(() => !!(window as any).__slicerSpike) // eslint-disable-line

  const warm = await app.ev((c) => (window as any).__slicerSpike.warmUp()) // eslint-disable-line
  console.log('engine ready', JSON.stringify(warm))
  expect(warm.variant).toBe('st')

  const a1 = await slice(app, 'a1')
  save('cube-a1', a1)
  const mk = await slice(app, 'mk4s')
  save('cube-mk4s', mk)
  // a second slice on the warm engine, for the steady-state time
  const again = await slice(app, 'a1')

  for (const r of [a1, mk]) {
    expect(r.gcode).toMatch(/^; (HEADER_BLOCK_START|generated by)/m)
    expect(r.gcode).toMatch(/generated by OrcaSlicer|BambuStudio|OrcaSlicer/)
    expect(r.layerCount ?? 0).toBeGreaterThanOrEqual(98)
    expect(r.layerCount ?? 0).toBeLessThanOrEqual(102)
    expect(r.stats.layers ?? 0).toBeGreaterThanOrEqual(98)
    expect(r.stats.filamentMm ?? 0).toBeGreaterThan(0)
    expect(r.stats.filamentG ?? 0).toBeGreaterThan(0)
    expect(r.stats.printTimeSeconds ?? 0).toBeGreaterThan(0)
    expect(r.extrusionSegments).toBeGreaterThan(1000)
    expect(r.layerZ.at(-1)).toBeCloseTo(20, 1)
  }
  expect(a1.gcode).toContain('Bambu Lab A1')
  expect(mk.gcode).toMatch(/MK4S/)

  const size = (f: string) => {
    const b = fs.readFileSync(path.join(ENGINE, f))
    return { raw: b.length, gzip: zlib.gzipSync(b, { level: 9 }).length, brotli: zlib.brotliCompressSync(b, { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11, [zlib.constants.BROTLI_PARAM_SIZE_HINT]: b.length } }).length }
  }
  const dirBytes = (d: string): number => fs.readdirSync(d, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? dirBytes(path.join(d, e.name)) : fs.statSync(path.join(d, e.name)).size), 0)
  const engineFiles = fs.readdirSync(ENGINE)
  const measurements = {
    wasm: size('engine-st.wasm'),
    mjs: size('engine-st.mjs'),
    hostService: size(engineFiles.find((f) => f.startsWith('host-service'))!),
    engineDirBytes: dirBytes(ENGINE),
    profilesDirBytes: dirBytes(PROFILES),
    warm,
    cubeA1: { ms: a1.ms, engine: a1.engineTimings, heap: a1.heapBytes, gcodeBytes: a1.gcodeBytes, stats: a1.stats, progressEvents: a1.progressEvents },
    cubeMk4s: { ms: mk.ms, engine: mk.engineTimings, heap: mk.heapBytes, gcodeBytes: mk.gcodeBytes, stats: mk.stats },
    cubeA1Again: { ms: again.ms, engine: again.engineTimings, heap: again.heapBytes },
  }
  fs.writeFileSync(path.join(OUT, 'measurements.json'), JSON.stringify(measurements, null, 1))
  console.log(JSON.stringify(measurements))
})

test('slicer spike: a two-color plate (painted face and painted body) gets filament changes on the A1', async ({ app }) => {
  test.setTimeout(240_000)
  await app.open()
  await addBox(app, [20, 20, 20], [0, 0, 0])
  await addBox(app, [20, 20, 20], [40, 0, 0])
  await app.page.waitForFunction(() => !!(window as any).__slicerSpike) // eslint-disable-line
  await app.tab('Print')
  // box 2 as a whole body to filament 2
  await app.ev((c) => c.ui.getState().setSelection([{ kind: 'body', id: c.doc.getState().geometry[1].id }]))
  await app.ribbon('Paint Body').click()
  await selectField(app, 'Filament', 'Filament 2')
  await app.ok()
  // box 1: its top face to filament 2
  const top = await app.ev((c) => {
    const m = c.doc.getState().geometry[0].mesh
    for (let t = 0; t < m.indices.length / 3; t++) if (m.normals[m.indices[t * 3] * 3 + 2] > 0.99) return m.faceIds[t] as number
    return -1
  })
  await app.ev((c, i) => { c.ui.getState().setSelectionFilter('face'); c.ui.getState().setSelection([{ kind: 'face', id: c.doc.getState().geometry[0].id, index: i }]) }, top)
  await app.ribbon('Paint Faces').click()
  await selectField(app, 'Filament', 'Filament 2')
  await app.ok()
  expect((await app.features()).filter((f) => f.type === 'paint').map((f) => f.params.slot)).toEqual(['2', '2'])
  const r = await slice(app, 'a1')
  save('twocolor-a1', r)
  expect(r.filaments).toBe(2)
  expect(r.gcode).toMatch(/^M620 S\d+/m)
  expect(r.gcode).toMatch(/^T1\b/m)
  console.log('twocolor', JSON.stringify({ layers: r.layerCount, m620: count(r.gcode, /^M620 S/gm), t1: count(r.gcode, /^T1\b/gm), stats: r.stats, ms: r.ms, warnings: r.warnings }))
})
