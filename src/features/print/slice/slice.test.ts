import { createHash } from 'node:crypto'
import { strFromU8, unzipSync } from 'fflate'
import { describe, expect, it } from 'vitest'
import { resolveParams } from '@/doc/params'
import { defaultSettings, printSettingsSchema, settingsFromValues } from '../settings'
import { writeBambu3mf, type GcodeExtras } from '../threemf'
import { bedOriginOf } from './bedOrigin'
import { md5Hex } from './md5'
import { legacyMachine, legacyProfile, parseProfile, serializeProfile } from './profile'
import { flatProjectConfig } from './projectConfig'
import { parseThumbnailSpec, thumbnailBlock } from './thumbnail'

const png = Uint8Array.from([0x89, 0x50, 0x4e, 0x47])
const cube = { positions: Float32Array.from([0, 0, 0, 10, 0, 0, 0, 10, 0, 0, 0, 10]), indices: Uint32Array.from([0, 2, 1, 0, 1, 3, 1, 2, 3, 0, 3, 2]) }

describe('.gcode.3mf assembly', () => {
  const gcode = new TextEncoder().encode('; HEADER_BLOCK_START\n; generated by OrcaSlicer\nG1 X1 Y1 E1\n')
  const extras: GcodeExtras = {
    gcode, md5: md5Hex(gcode), images: { plate: png, small: png, noLight: png, top: png, pick: png },
    info: { prediction: 1200, weight: 3.67, nozzle: 0.4, printerModelId: 'N2S', firstLayerTime: 368, supportUsed: false, layerCount: 100, layerHeight: 0.2, bedType: 'cool_plate',
      filaments: [{ id: 1, type: 'PLA', color: '#F2754E', usedM: 1.21, usedG: 3.67, trayInfoIdx: 'GFA00' }] },
  }
  const full = flatProjectConfig(
    {
      machine: { printer_model: 'Bambu Lab A1', nozzle_diameter: ['0.4'], type: 'machine' }, process: { layer_height: '0.28', type: 'process' },
      filaments: [{ filament_type: ['PLA'], filament_colour: ['#F2754E'], filament_id: 'GFA00' }], processName: '0.28mm Extra Draft @BBL A1', filamentNames: ['Bambu PLA Basic @BBL A1'],
      base: { machine: {}, process: {}, filaments: [{}] }, plate: null,
    },
    { ...legacyProfile({}), overrides: { machine: {}, process: { layer_height: '0.28' }, filaments: [{}] } },
  )
  const bytes = writeBambu3mf([{ name: 'cube', ...cube, id: 'f1', config: { sparse_infill_density: '100%' }, paint: { supports: Uint8Array.from([1, 0, 0, 0]) } }], [{ offset: [128, 128, 10] }], defaultSettings(), 'BambuStudio-2.3.2', extras, full)
  const z = unzipSync(bytes)

  it('has the file list desktop OrcaSlicer writes', () => {
    expect(Object.keys(z).sort()).toEqual([
      '3D/3dmodel.model', '3D/Objects/object_1.model', '3D/_rels/3dmodel.model.rels', '[Content_Types].xml', '_rels/.rels',
      'Metadata/_rels/model_settings.config.rels', 'Metadata/model_settings.config', 'Metadata/pick_1.png', 'Metadata/plate_1.gcode', 'Metadata/plate_1.gcode.md5',
      'Metadata/plate_1.json', 'Metadata/plate_1.png', 'Metadata/plate_1_small.png', 'Metadata/plate_no_light_1.png', 'Metadata/project_settings.config',
      'Metadata/slice_info.config', 'Metadata/top_1.png',
    ].sort())
  })

  it('writes the G-code unchanged with its uppercase md5', () => {
    expect(z['Metadata/plate_1.gcode']).toEqual(gcode)
    expect(strFromU8(z['Metadata/plate_1.gcode.md5'])).toBe(createHash('md5').update(gcode).digest('hex').toUpperCase())
    expect(md5Hex(new Uint8Array(0))).toBe('D41D8CD98F00B204E9800998ECF8427E')
    const big = new Uint8Array(1000).map((_, i) => i * 7)
    expect(md5Hex(big)).toBe(createHash('md5').update(big).digest('hex').toUpperCase())
  })

  it('carries the presets as sliced, the plate numbers and the per-object paint and settings', () => {
    const cfg = JSON.parse(strFromU8(z['Metadata/project_settings.config']))
    expect(cfg).toMatchObject({ from: 'project', layer_height: '0.28', print_settings_id: '0.28mm Extra Draft @BBL A1', filament_settings_id: ['Bambu PLA Basic @BBL A1'], filament_type: ['PLA'] })
    expect(cfg.different_settings_to_system).toEqual(['layer_height', '', ''])
    expect(cfg.type).toBeUndefined()
    const info = strFromU8(z['Metadata/slice_info.config'])
    expect(info).toContain('key="prediction" value="1200"')
    expect(info).toContain('<filament id="1" tray_info_idx="GFA00" type="PLA" color="#F2754E" used_m="1.21" used_g="3.67" />')
    expect(JSON.parse(strFromU8(z['Metadata/plate_1.json']))).toMatchObject({ bbox_all: [128, 128, 138, 138], filament_colors: ['#F2754E'], version: 2 })
    expect(strFromU8(z['Metadata/model_settings.config'])).toContain('<metadata key="sparse_infill_density" value="100%"/>')
    expect(strFromU8(z['Metadata/model_settings.config'])).toContain('gcode_file" value="Metadata/plate_1.gcode"')
    expect(strFromU8(z['3D/Objects/object_1.model'])).toContain('paint_supports="4"')
    expect(strFromU8(z['Metadata/_rels/model_settings.config.rels'])).toContain('package/2021/gcode')
  })
})

describe('thumbnails', () => {
  it('reads Orca thumbnail sizes and writes the block format', () => {
    expect(parseThumbnailSpec('16x16/QOI, 313x173/QOI, 640x480/PNG, 200x200/COLPIC')).toEqual([
      { w: 16, h: 16, format: 'QOI' }, { w: 313, h: 173, format: 'QOI' }, { w: 640, h: 480, format: 'PNG' },
    ].sort())
    const block = thumbnailBlock({ w: 48, h: 48, format: 'PNG' }, png)
    expect(block).toBe('; thumbnail begin 48x48 8\n; iVBORw==\n; thumbnail end\n')
  })
})

describe('legacy printer ids', () => {
  it('map to the matching Bambu machine preset with the old nozzle', () => {
    expect(legacyMachine('a1')).toBe('Bambu Lab A1 0.4 nozzle')
    expect(legacyMachine('a1mini', '0.6')).toBe('Bambu Lab A1 mini 0.6 nozzle')
    expect(legacyMachine('x1c')).toBe('Bambu Lab X1 Carbon 0.4 nozzle')
    expect(legacyMachine('nope')).toBeNull()
  })

  it('an old Print settings feature opens with its printer, bed and values as the profile', () => {
    const raw = { printer: 'a1mini', nozzle: '0.6', layerHeight: 0.16, wallLoops: 4, infill: 25, support: 'tree' }
    const s = settingsFromValues(resolveParams(printSettingsSchema, raw), raw)
    expect(s.printer).toMatchObject({ id: 'Bambu Lab A1 mini 0.6 nozzle', bed: [180, 180] })
    expect(s.nozzle).toBe(0.6)
    expect(s.profile.overrides.process).toMatchObject({ layer_height: '0.16', wall_loops: '4', sparse_infill_density: '25%', enable_support: '1', support_type: 'tree(auto)' })
  })

  it('a stored profile round trips and wins over the old fields', () => {
    const p = { ...legacyProfile({ printer: 'p1s' }), process: '0.20mm Standard @BBL X1C' }
    expect(parseProfile(serializeProfile(p))).toMatchObject({ machine: 'Bambu Lab P1S 0.4 nozzle', process: '0.20mm Standard @BBL X1C' })
    const raw = { printer: 'a1', slicing: serializeProfile(p) }
    expect(settingsFromValues(resolveParams(printSettingsSchema, raw), raw).printer.id).toBe('Bambu Lab P1S 0.4 nozzle')
  })
})

describe('bed origin', () => {
  const box = (x: number, y: number, z: number) => ({ positions: Float32Array.from([x, y, z, x + 20, y + 20, z + 20]) })
  it('is minus the placement offset for a kept plate', () => {
    // bodies at x 30..50, plate 256 wide: the offset centres them, so the bed origin sits 128 - 40 = 88 mm before them
    const o = bedOriginOf([box(30, -10, 5)], [box(118, 118, 0)])
    expect(o).toEqual([-88, -128, 5])
  })
  it('follows the bounding box when the plate arranged the parts', () => {
    const o = bedOriginOf([box(0, 0, 0), box(100, 0, 0)], [box(80, 118, 0), box(110, 118, 0)])
    expect(o).toEqual([-45, -118, 0])
  })
})
